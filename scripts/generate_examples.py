"""Generate kernel-checked deletion-contraction certificates for the paper examples.

Only the emitted Lean proofs are trusted. Sympy provides candidate right-hand sides;
Lean verifies every recurrence and every polynomial identity with `ring`.
"""
from functools import lru_cache
from pathlib import Path
import sympy as sp

P = sp.symbols('p0:8')
records = []


def weights(w):
    return '![' + ', '.join(map(str, w)) + ']'


def edges(E):
    return '{' + ', '.join(f'({a}, {b})' for a, b in E) + '}' if E else '∅'


def expression(q):
    if q == 0:
        return '0'
    terms = []
    for powers, coeff in sp.Poly(q, *P).terms():
        factors = []
        c = abs(int(coeff))
        if c != 1 or not any(powers):
            factors.append(str(c))
        for k, m in enumerate(powers):
            if m:
                factors.append(f'p N {k}' + (f' ^ {m}' if m != 1 else ''))
        term = ' * '.join(factors)
        terms.append(('-' if coeff < 0 else '+', term))
    first, *rest = terms
    return ('-' if first[0] == '-' else '') + first[1] + ''.join(f' {sign} {term}' for sign, term in rest)


@lru_cache(None)
def certificate(w, E):
    n = len(w)
    loop = next((a for a, b in E if a == b), None)
    if loop is not None:
        result, kind, data = sp.Integer(0), 'loop', loop
    elif not n:
        result, kind, data = sp.Integer(1), 'empty', None
    else:
        inc = [a for a, b in E if b == n - 1]
        if not inc:
            child, q = certificate(w[:-1], E)
            result, kind, data = sp.expand(P[w[-1]] * q), 'isolated', child
        else:
            u = inc[0]
            tail = tuple(x for x in E if x != (u, n - 1))
            neww = list(w[:-1])
            neww[u] += w[-1]
            def f(x):
                return u if x == n - 1 else x
            newe = tuple(sorted(set(tuple(sorted((f(a), f(b)))) for a, b in tail)))
            left, ql = certificate(w, tail)
            right, qr = certificate(tuple(neww), newe)
            result, kind, data = sp.expand(ql - qr), 'edge', (u, tail, tuple(neww), newe, left, right)
    i = len(records)
    records.append((w, E, result, kind, data))
    return i, result


p3, _ = certificate((1,)*3, ((0, 1), (1, 2)))
p2, _ = certificate((1,)*2, ((0, 1),))
six, _ = certificate((1,)*6, ((0, 1), (0, 2), (0, 5), (1, 2), (1, 5), (2, 3), (3, 4), (4, 5)))
seven, _ = certificate((1,)*7, ((0, 1), (0, 2), (1, 2), (2, 3), (3, 4), (3, 5), (4, 5), (4, 6), (5, 6)))

out = ['''import ProperCircularArc.DeletionContraction

/-!
# Certificates for the worked examples

Generated by `scripts/generate_examples.py`. Each step is checked by Lean's kernel.
The right-hand sides are power-sum polynomials, later converted by Newton identities.
-/

namespace ProperCircularArc.Examples

open MvPolynomial Finset

noncomputable def p (N k : ℕ) : Pol N := psum (Fin N) ℚ k

set_option maxRecDepth 4096
set_option maxHeartbeats 2000000
''']
for i, (w, E, q, kind, data) in enumerate(records):
    out.append(f'private theorem cert_{i} (N : ℕ) :\n    weightedCSF N {weights(w)} {edges(E)} =\n      {expression(q)} := by\n')
    if kind == 'loop':
        out.append(f'  exact weightedCSF_loop N _ _ {data} (by decide)\n')
    elif kind == 'empty':
        out.append('  simp [weightedCSF]\n')
    elif kind == 'isolated':
        out.append(f'  have he : ({edges(E)} : Finset (Fin {len(w)} × Fin {len(w)})) =\n      ({edges(E)} : Finset (Fin {len(w)-1} × Fin {len(w)-1})).image\n        (fun e => (e.1.castSucc, e.2.castSucc)) := by decide\n')
        out.append('  rw [he, weightedCSF_isolated]\n')
        out.append(f'  change p N {w[-1]} * weightedCSF N {weights(w[:-1])} {edges(E)} = _\n')
        out.append(f'  rw [cert_{data}]\n  all_goals ring\n')
    else:
        u, tail, neww, newe, left, right = data
        n = len(w)-1
        out.append(f'  have he : ({edges(E)} : Finset (Fin {n+1} × Fin {n+1})) =\n      insert (({u} : Fin {n}).castSucc, Fin.last {n}) {edges(tail)} := by decide\n')
        out.append('  rw [he, weightedCSF_delete_contract]\n')
        out.append(f'  have hw : contractWeight ({weights(w)} : Fin {n+1} → ℕ) {u} = {weights(neww)} := by decide\n')
        out.append(f'  have hc : contractEdges ({edges(tail)} : Finset (Fin {n+1} × Fin {n+1})) {u} = {edges(newe)} := by decide\n')
        # Orientation is immaterial to proper colourings. The map can produce reversed edges.
        # Normalize these explicitly with weightedCSF_congr if the raw image differs.
        raw = tuple(sorted(set((u if a == n else a, u if b == n else b) for a,b in tail)))
        if raw != newe:
            out[-1] = f'  have hc : contractEdges ({edges(tail)} : Finset (Fin {n+1} × Fin {n+1})) {u} = {edges(raw)} := by decide\n'
            out.append(f'  have hn : weightedCSF N {weights(neww)} {edges(raw)} = weightedCSF N {weights(neww)} {edges(newe)} := by\n')
            out.append('    apply weightedCSF_congr N rfl\n    intro c\n    simp [ne_comm]\n    all_goals tauto\n')
            out.append(f'  rw [hw, hc, hn, cert_{left}, cert_{right}]\n  all_goals ring\n')
        else:
            out.append(f'  rw [hw, hc, cert_{left}, cert_{right}]\n  all_goals ring\n')
    out.append('\n')
for name, i in [('path3_power',p3), ('path2_power',p2), ('six_power',six), ('seven_power',seven)]:
    w,E,q,*_ = records[i]
    out.append(f'theorem {name} (N : ℕ) :\n    weightedCSF N {weights(w)} {edges(E)} =\n      {expression(q)} := cert_{i} N\n\n')
out.append('end ProperCircularArc.Examples\n')
Path('ProperCircularArc/ExamplesCertificates.lean').write_text(''.join(out))
print(f'{len(records)} certificates; final indices: {p3}, {p2}, {six}, {seven}')
